export function createInitialFlights(): Flight[] {
  const now = Date.now();
  const scratch = new THREE.Vector3();

  return SEED_FLIGHTS.map((seed) => {
    const orig = AIRPORT_MAP[seed.origin];
    const dest = AIRPORT_MAP[seed.destination];
    const distanceKm = calculateDistanceKm(orig.lat, orig.lon, dest.lat, dest.lon);
    const durationMinutes = Math.max(50, Math.round((distanceKm / 780) * 60 + 25));
    const durationMs = durationMinutes * 60 * 1000;
    const delayMinutes = seed.delayMinutes ?? 0;
    const delayMs = delayMinutes * 60 * 1000;

    let scheduledDepartureMs: number;
    if (seed.progress > 0 && seed.progress < 1) {
      scheduledDepartureMs = now - Math.round(seed.progress * durationMs) - delayMs;
    } else if (seed.progress >= 1) {
      scheduledDepartureMs = now - durationMs - 6 * 60 * 1000;
    } else {
      scheduledDepartureMs = now + (seed.status === 'TERTUNDA' ? -10 : 14) * 60 * 1000;
    }

    const estimatedDepartureMs = scheduledDepartureMs + delayMs;
    const scheduledArrivalMs = scheduledDepartureMs + durationMs;
    const estimatedArrivalMs = estimatedDepartureMs + durationMs;

    getFlightArcPoint(
      orig.lat,
      orig.lon,
      dest.lat,
      dest.lon,
      seed.progress,
      distanceKm,
      scratch
    );
    const { lat, lon } = vector3ToLatLon(scratch);
    const headingDeg = calculateBearingDeg(lat, lon, dest.lat, dest.lon);

    const isAirborne =
      seed.status === 'BERANGKAT' ||
      seed.status === 'MENGUDARA' ||
      seed.status === 'MENDEKAT';

    return {
      id: seed.id,
      flightNumber: seed.flightNumber,
      airline: seed.airline,
      airlineColor: seed.airlineColor,
      aircraftType: seed.aircraftType,
      registration: seed.registration,
      origin: seed.origin,
      destination: seed.destination,
      status: seed.status,
      progress: seed.progress,
      cruiseSpeedKts: seed.cruiseSpeedKts,
      speedKts: isAirborne
        ? computeLiveSpeedKts(seed.progress, seed.cruiseSpeedKts)
        : 0,
      cruiseAltitudeFt: seed.cruiseAltitudeFt,
      altitudeFt: isAirborne
        ? computeLiveAltitudeFt(seed.progress, seed.cruiseAltitudeFt)
        : 0,
      headingDeg,
      lat,
      lon,
      scheduledDepartureMs,
      estimatedDepartureMs,
      scheduledArrivalMs,
      estimatedArrivalMs,
      delayMinutes,
      departureTerminal: seed.depTerm,
      departureGate: seed.depGate,
      arrivalTerminal: seed.arrTerm,
      arrivalGate: seed.arrGate,
      durationMinutes,
      distanceKm,
      groundPhaseTimerSec: seed.groundPhaseTimerSec ?? 20,
      statusNote: seed.statusNote,
    };
  });
}
